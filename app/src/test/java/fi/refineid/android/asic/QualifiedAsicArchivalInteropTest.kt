package fi.refineid.android.asic

import fi.refineid.android.core.NativeCardKeyProfile
import fi.refineid.android.document.ArchivalLevelPolicy
import fi.refineid.android.document.DocumentValidationResult
import fi.refineid.android.document.PadesInteropEnvironment
import fi.refineid.android.document.QualifiedPdfTimestampSource
import fi.refineid.android.document.QualifiedPdfValidationSource
import fi.refineid.android.document.ValidationMaterialCollectionRequest
import fi.refineid.android.document.ValidationMaterialCollector
import fi.refineid.android.document.VerifiedTimestampAuthority
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.ByteArrayInputStream
import java.nio.file.Files
import java.nio.file.Path
import java.security.MessageDigest
import java.security.cert.CertificateFactory
import java.security.cert.X509Certificate
import java.time.Instant
import java.util.Base64

/**
 * XAdES-B-LTA over a real card-equivalent signature, a real RFC 3161
 * authority and authenticated validation material, all generated by
 * OpenSSL in a temporary directory. OpenSSL independently checks both
 * timestamp tokens against digests recomputed from the written XML.
 */
class QualifiedAsicArchivalInteropTest {
    @Test
    fun archiveTimestampImprintsTheWrittenSignatureAndTheContainerValidates() {
        val environment = PadesInteropEnvironment.discover()
        assumeTrue("OpenSSL, qpdf, and pdfsig are required for the XAdES-B-LTA test", environment != null)
        checkNotNull(environment).use { tools ->
            VerifiedTimestampAuthority.create(tools).use { authority ->
                val certificate = tools.generateQualifiedCertificate()
                val objects =
                    listOf(
                        AsicDataObject(FIRST_NAME, FIRST_CONTENT.encodeToByteArray(), TEXT_MEDIA_TYPE),
                        AsicDataObject(SECOND_NAME, SECOND_CONTENT.encodeToByteArray(), TEXT_MEDIA_TYPE),
                    )
                val plan =
                    XadesSignature.plan(
                        profile = NativeCardKeyProfile.RSA_3072,
                        objects = objects,
                        certificateDer = certificate,
                        signedAt = SIGNED_AT,
                    )
                val prepared =
                    PreparedAsicSignature(
                        plan = plan,
                        objects = objects,
                        rawSignature = tools.sign(plan.signedInfo.encodeToByteArray()),
                        certificateDer = certificate.copyOf(),
                    )
                val result =
                    QualifiedAsicArchivalCompletion.complete(
                        prepared = prepared,
                        timestampSource = QualifiedPdfTimestampSource(authority::issue),
                        validationSource = validationSource(tools),
                        policy = ArchivalLevelPolicy.LONG_TERM_ONLY,
                    )

                val container = (result as AsicSigningResult.Success).container
                val xml = XadesArchiveInputReading.signatureXml(container)
                tools.validateTimestampToken(
                    XadesArchiveInputReading.archiveTimestampToken(xml),
                    XadesArchiveInputReading.archiveDigest(container),
                )
                tools.validateTimestampToken(
                    signatureTimestampToken(xml),
                    MessageDigest
                        .getInstance(DIGEST_ALGORITHM)
                        .digest(XadesArchiveInputReading.element(xml, SIGNATURE_VALUE).encodeToByteArray()),
                )
                assertContainerValidates(container, certificate)
                System.getenv(SAMPLE_OUTPUT_VARIABLE)?.let { output -> Files.write(Path.of(output), container) }
            }
        }
    }

    private fun validationSource(environment: PadesInteropEnvironment): QualifiedPdfValidationSource =
        QualifiedPdfValidationSource { signerCertificate, signatureTimestamp ->
            ValidationMaterialCollector.collect(
                request =
                    ValidationMaterialCollectionRequest(
                        signerCertificate = signerCertificate,
                        timestampTokens = listOf(signatureTimestamp),
                        signerTrustCertificates = listOf(signerCertificate),
                    ),
                dependencies = environment.validationDependencies(signatureTimestamp.generatedAt),
            )
        }

    private fun assertContainerValidates(
        container: ByteArray,
        certificate: ByteArray,
    ) {
        val anchor =
            CertificateFactory
                .getInstance(CERTIFICATE_TYPE)
                .generateCertificate(ByteArrayInputStream(certificate)) as X509Certificate
        val result = AsicValidator.validate(container, listOf(anchor)) as DocumentValidationResult.Completed
        val verdict = result.signatures.single()
        assertTrue(verdict.digestMatches)
        assertTrue(verdict.signatureValid)
        assertTrue(verdict.chainTrusted)
        assertTrue(verdict.hasSignatureTimestamp)
        assertTrue(verdict.coversWholeDocument)
    }

    private fun signatureTimestampToken(xml: String): ByteArray {
        val element = XadesArchiveInputReading.element(xml, SIGNATURE_TIMESTAMP)
        val start = element.indexOf(ENCAPSULATED_TIMESTAMP_START) + ENCAPSULATED_TIMESTAMP_START.length
        return Base64.getDecoder().decode(element.substring(start, element.indexOf(ENCAPSULATED_TIMESTAMP_END)))
    }

    private companion object {
        const val FIRST_NAME = "agreement.txt"
        const val SECOND_NAME = "appendix.txt"
        const val FIRST_CONTENT = "synthetic agreement text"
        const val SECOND_CONTENT = "synthetic appendix text"
        const val TEXT_MEDIA_TYPE = "text/plain"
        const val DIGEST_ALGORITHM = "SHA-384"
        const val CERTIFICATE_TYPE = "X.509"
        const val SIGNATURE_VALUE = "ds:SignatureValue"
        const val SIGNATURE_TIMESTAMP = "xades:SignatureTimeStamp"
        const val ENCAPSULATED_TIMESTAMP_START = "<xades:EncapsulatedTimeStamp>"
        const val ENCAPSULATED_TIMESTAMP_END = "</xades:EncapsulatedTimeStamp>"

        /** When set, the path one finished container is written to for cross-checking with other verifiers. */
        const val SAMPLE_OUTPUT_VARIABLE = "REFINEID_LTA_SAMPLE_OUT"
        val SIGNED_AT: Instant = Instant.parse("2026-11-08T12:00:00Z")
    }
}
